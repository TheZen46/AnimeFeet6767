"""Controlli simbolici dei conti dei moduli di Analisi 1B. Uso: python verifica.py"""
from sympy import *
t,x,y,z,k,m,g,h0,a,b,n,lam=symbols('t x y z k m g h0 a b n lambda',real=True)
ok=[]
def chk(nome,cond):
    ok.append(bool(cond)); print(('ok  ' if cond else 'ERR ')+nome)
# modulo 1
chk('ln x', simplify(diff(x*log(x)-x,x)-log(x))==0)
chk('x e^{x^2}', simplify(diff(exp(x**2)/2,x)-x*exp(x**2))==0)
chk('tan', simplify(diff(-log(cos(x)),x)-tan(x))==0)
chk('e^x/(1+e^2x)', simplify(diff(atan(exp(x)),x)-exp(x)/(1+exp(2*x)))==0)
chk('razionale delta>0', simplify(diff(log(x-2)-log(x-1),x)-1/(x**2-3*x+2))==0)
chk('razionale delta<0', simplify(diff(atan((x+1)/2)/2,x)-1/(x**2+2*x+5))==0)
chk('area 1/6', integrate(x-x**2,(x,0,1))==Rational(1,6))
chk('16/15', simplify(integrate(x**2/sqrt(1-x),(x,0,1))-Rational(16,15))==0)
chk('x^2 e^x', simplify(diff(exp(x)*(x**2-2*x+2),x)-x**2*exp(x))==0)
chk('x e^-x', integrate(x*exp(-x),(x,0,oo))==1)
chk('1/(1+x^2)', integrate(1/(1+x**2),(x,0,oo))==pi/2)
chk('sin|x| primitiva continua', limit(-cos(x)+2,x,0)==limit(cos(x),x,0))
# modulo 2
N=symbols('N',integer=True,positive=True)
chk('mengoli', limit(1-1/(N+1),N,oo)==1)
chk('geometrica 1/2', summation(Rational(1,2)**n,(n,0,oo))==2)
chk('alterna -ln2', summation((-1)**n/n,(n,1,oo))==-log(2))
chk('n!/n^n rapporto', limit((n/(n+1))**n,n,oo)==exp(-1))
chk('(n+3)/(2n^2+5)', limit(n*(n+3)/(2*n**2+5),n,oo)==Rational(1,2))
# modulo 3
f=sin(x*y**2/(1+z**2)); gr=[diff(f,v).subs({x:0,y:1,z:1}) for v in (x,y,z)]
chk('gradiente (1/2,0,0)', gr==[Rational(1,2),0,0])
f=x**3+y**3+x*y; chk('piano tangente', [diff(f,x).subs({x:1,y:1}),diff(f,y).subs({x:1,y:1}),f.subs({x:1,y:1})]==[4,4,3])
f=x**2+y**3; chk('derivata direzionale 3', limit((f.subs({x:h0,y:1+h0})-1)/h0,h0,0)==3)
f=x**3-3*x+y**2; H=hessian(f,(x,y))
chk('critici x^3-3x+y^2', solve([diff(f,x),diff(f,y)],[x,y],dict=True)==[{x:-1,y:0},{x:1,y:0}] and H.subs({x:1,y:0}).det()==12 and H.subs({x:-1,y:0}).det()==-12)
f=(y-x**2)*(y-2*x**2); chk('Peano espansione', expand(f)==y**2-3*x**2*y+2*x**4 and hessian(f,(x,y)).subs({x:0,y:0})==Matrix([[0,0],[0,2]]))
f=x**2+y**2-2*x; chk('estremi sul disco', f.subs({x:1,y:0})==-1 and (4-2*x).subs(x,-2)==8)
# modulo 4
Y=Function('Y')
sol=h0-m*g/k*t+m**2*g/k**2*(1-exp(-k*t/m))
chk('caduta con attrito', simplify(m*diff(sol,t,2)+m*g+k*diff(sol,t))==0 and sol.subs(t,0)==h0 and simplify(diff(sol,t).subs(t,0))==0)
K,P0,e=symbols('K P0 epsilon',positive=True)
L=K*P0*exp(e*t)/(K-P0+P0*exp(e*t)); chk('logistica generale', simplify(diff(L,t)-e*L*(1-L/K))==0)
yl=2*exp(2*t)/(2*exp(2*t)-1); chk('logistica y(0)=2', simplify(diff(yl,t)-2*yl*(1-yl))==0 and yl.subs(t,0)==2)
tp=symbols('tp',positive=True); yp=(2*tp/3)**Rational(3,2); chk('Peano', simplify(diff(yp,tp)-yp**Rational(1,3))==0)
y1=1+2*exp(cos(t)-1); chk('lineare -sin t', simplify(diff(y1,t)-(-sin(t)*y1+sin(t)))==0 and simplify(y1.subs(t,0))==3)
yy=t**2-2; chk("y''+y=t^2", simplify(diff(yy,t,2)+yy-t**2)==0)
yy=-t*exp(t); chk("y''-3y'+2y=e^t", simplify(diff(yy,t,2)-3*diff(yy,t)+2*yy-exp(t))==0)
yy=sqrt(t**2+4); chk("y'=t/y", simplify(diff(yy,t)-t/yy)==0)
tt=symbols('tt',positive=True); al=symbols('alpha'); yy=tt**4/2+al*tt**2; chk("y'=2y/t+t^3", simplify(diff(yy,tt)-(2*yy/tt+tt**3))==0)
chk("y'=y^2", simplify(diff(1/(1-t),t)-(1/(1-t))**2)==0)
A=Matrix([[2,3],[2,1]]); chk('2x2', A*Matrix([3,2])==4*Matrix([3,2]) and A*Matrix([1,-1])==-Matrix([1,-1]))
A=Matrix([[0,1,-1],[2,1,6],[0,1,-1]]); chk('3x3', A*Matrix([7,-2,-2])==zeros(3,1) and A*Matrix([1,4,1])==3*Matrix([1,4,1]) and A*Matrix([1,-2,1])==-3*Matrix([1,-2,1]) and factor((A-lam*eye(3)).det())==factor(-lam*(lam-3)*(lam+3)))
A=Matrix([[0,1,0],[0,0,1],[0,-4,4]]); v0=Matrix([1,2,4]); v1=Matrix([0,1,4])
w=(v1+t*v0)*exp(2*t)
chk('carente', factor((A-lam*eye(3)).det())==factor(-lam*(lam-2)**2) and (A-2*eye(3))*v0==zeros(3,1) and (A-2*eye(3))*v1==v0 and simplify(diff(w,t)-A*w)==zeros(3,1) and simplify(w/exp(2*t)-Matrix([t,1+2*t,4+4*t]))==zeros(3,1))
A=Matrix([[0,1],[-1,0]]); s1=Matrix([cos(t),-sin(t)]); s2=Matrix([sin(t),cos(t)])
chk('complessi', simplify(diff(s1,t)-A*s1)==zeros(2,1) and simplify(diff(s2,t)-A*s2)==zeros(2,1))
B=Matrix([[1,1,0],[0,0,1],[-1,3,-1]]); chk('esempio della dispensa NON torna (atteso)', factor((B-lam*eye(3)).det())!=factor(-lam*(lam-2)**2))
print('TUTTO OK' if all(ok) else 'CI SONO ERRORI')
